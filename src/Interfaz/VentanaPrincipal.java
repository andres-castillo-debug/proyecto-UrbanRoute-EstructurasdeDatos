    /**
    * Actualiza la lista de estaciones en la interfaz.
    */
    private void actualizarListaEstaciones() {
        modeloListaEstaciones.removeAllElements();
        EDD.Lista<EDD.Estacion> estaciones = grafo.getTodasEstaciones();
        for (int i = 0; i < estaciones.getTamaño(); i++) {
            EDD.Estacion e = estaciones.obtener(i);
            modeloListaEstaciones.addElement(e.getId() + " - " + e.getNombre());
        }
    }
    
    /**
    * Actualiza los combos de origen y destino.
    */
    private void actualizarCombos() {
        modeloOrigen.removeAllElements();
        modeloDestino.removeAllElements();
        EDD.Lista<EDD.Estacion> estaciones = grafo.getTodasEstaciones();
        for (int i = 0; i < estaciones.getTamaño(); i++) {
            String id = estaciones.obtener(i).getId();
            modeloOrigen.addElement(id);
            modeloDestino.addElement(id);
        }
    }
    
    /**
    * Actualiza la información mostrada en la interfaz.
    */
    private void actualizarInfo() {
        lblArchivoEstaciones.setText("Estaciones: " + 
            GestorArchivo.getNombreArchivoEstaciones());
        lblArchivoConexiones.setText("Conexiones: " + 
            GestorArchivo.getNombreArchivoConexiones());
        lblStats.setText("Estaciones: " + grafo.getNumEstaciones() + 
                        " | Conexiones: " + grafo.getNumAristas());
    }

